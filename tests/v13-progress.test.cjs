// JI BUS V1.3 Build 07 — modal lifecycle and request cancellation
'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const app=fs.readFileSync(path.join(__dirname,'..','app.js'),'utf8');
const html=fs.readFileSync(path.join(__dirname,'..','index.html'),'utf8');
assert.match(html,/id="searchProgressOverlay"/);
assert.match(html,/id="searchProgressMessage"/);
assert.match(html,/id="searchProgressCancel"/);
assert.match(html,/role="dialog"/);
assert.match(html,/aria-modal="true"/);
assert.match(html,/searchProgressTrack/);
assert.match(html,/prefers-reduced-motion/);
assert.match(app,/searchProgressStep\(work,'실시간 버스 도착정보를 확인하고 있습니다/);
assert.match(app,/beginSearchProgress\('버스 경로를 찾고 있습니다'/);
assert.match(app,/beginSearchProgress\('최적의 버스 경로를 찾고 있습니다'/);
assert.match(app,/beginSearchProgress\('주변 정류장을 찾고 있습니다'/);
assert.match(app,/endSearchProgress\(work\)/);
assert.match(app,/controller\.abort\(\)/);
assert.match(app,/activeSearchProgress!==progress/);
assert.doesNotMatch(app,/setInterval\([^\n]*beginSearchProgress/);
const begin=app.indexOf('let activeSearchProgress=null;'),end=app.indexOf('const services=',begin);
assert(begin>=0&&end>begin);
const modal={hidden:true},message={textContent:''},title={textContent:''},cancel={focus(){},onclick:null};
const elements={searchProgressOverlay:modal,searchProgressMessage:message,searchProgressTitle:title,searchProgressCancel:cancel};
const $=id=>elements[id];
const timerCalls=[],cleared=[];
const setTimeout=(fn,ms)=>{timerCalls.push({fn,ms});return timerCalls.length};
const clearTimeout=(id)=>cleared.push(id);
const obj=new Function('$','setTimeout','clearTimeout',app.slice(begin,end)+
 ';return {beginSearchProgress,searchProgressStep,endSearchProgress,cancelSearchProgress,getActive:()=>activeSearchProgress}')($,setTimeout,clearTimeout);
let cancelled=0;
const work=obj.beginSearchProgress('경로 확인',()=>cancelled++);
assert.equal(modal.hidden,true);
assert.equal(title.textContent,'경로 확인');
assert.equal(timerCalls.at(-1).ms,300);
obj.searchProgressStep(work,'정류장 확인 중');
assert.equal(message.textContent,'정류장 확인 중');
timerCalls.at(-1).fn();
assert.equal(modal.hidden,false);
const controller={aborts:0,abort(){this.aborts++}};
work.controllers.add(controller);
cancel.onclick();
assert.equal(modal.hidden,true);
assert.equal(controller.aborts,1);
assert.equal(cancelled,1);
assert.equal(obj.getActive(),null);
cancel.onclick();
assert.equal(cancelled,1,'duplicate cancel must be harmless');
obj.searchProgressStep(work,'늦게 도착한 결과');
assert.equal(message.textContent,'정류장 확인 중','stale result must not change message');
const fast=obj.beginSearchProgress('빠른 검색',()=>cancelled++);
obj.endSearchProgress(fast);
timerCalls.at(-1).fn();
assert.equal(modal.hidden,true,'fast search must never flash');
assert.equal(obj.getActive(),null);
assert.equal(cancelled,1);
console.log('JI BUS V1.3 Build 07 progress/cancel tests PASS (28 checks)');
