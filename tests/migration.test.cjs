// JI BUS V1.1 - legacy commute to route favorites migration
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const src=fs.readFileSync(path.join(__dirname,'..','app.js'),'utf8');
const start=src.indexOf('function validStop('),end=src.indexOf('migrateTrips();',start);
assert(start>=0&&end>start,'V1.1 migration functions missing');
const logic=src.slice(start,end);
const stop=(id,name)=>({id,name});
const board=stop('b','출근 승차'),exit=stop('e','출근 하차'),alt=stop('a','대체 하차');
const home=stop('h','귀가 도착'),returnStop=stop('r','귀가 승차');
let original={key:'PRIVATE_TEST_KEY',stops:{board,exit,alt,home},favorites:[returnStop],routes:[],last:'r',tripFavorites:[]};
const run=new Function('initial',`let cfg=initial;let writes=0;const save=()=>{writes++};${logic};migrateTrips();return {cfg,writes,migrateTrips,makeTrip,sameTrip}`);
let first=run(structuredClone(original));
assert.equal(first.cfg.key,'PRIVATE_TEST_KEY');
assert.equal(first.cfg.tripMigrationV11,true);
assert.equal(first.cfg.tripFavorites.length,2);
assert.equal(first.cfg.tripFavorites[0].title,'회사 출근');
assert.equal(first.cfg.tripFavorites[0].from.id,'b');
assert.equal(first.cfg.tripFavorites[0].alt.id,'a');
assert.equal(first.cfg.tripFavorites[1].title,'집으로 귀가');
assert.equal(first.cfg.tripFavorites[1].from.id,'r');
assert.equal(first.writes,1);
first.migrateTrips();
assert.equal(first.cfg.tripFavorites.length,2);
let withoutOrigin=structuredClone(original);withoutOrigin.favorites=[];withoutOrigin.last='';
const second=run(withoutOrigin);
assert.equal(second.cfg.tripFavorites.length,1);
assert.equal(second.cfg.tripFavorites[0].title,'회사 출근');
assert.deepEqual(second.cfg.stops,original.stops);
console.log('JI BUS V1.1 migration tests PASS (13 assertions)');
